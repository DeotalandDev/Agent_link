typedef struct {
    esp_lcd_panel_t base;
    esp_lcd_panel_io_handle_t io;
    int reset_gpio_num;
    int x_gap;
    int y_gap;
    uint8_t fb_bits_per_pixel;
    uint8_t madctl_val; // save current value of LCD_CMD_MADCTL register
    uint8_t colmod_val; // save surrent value of LCD_CMD_COLMOD register
    const sh8501_lcd_init_cmd_t *init_cmds;
    uint16_t init_cmds_size;
    struct {
        unsigned int use_qspi_interface: 1;
        unsigned int reset_level: 1;
    } flags;
} sh8501_panel_t;

esp_err_t esp_lcd_new_panel_sh8501(const esp_lcd_panel_io_handle_t io, const esp_lcd_panel_dev_config_t *panel_dev_config, esp_lcd_panel_handle_t *ret_panel)
{
    ESP_RETURN_ON_FALSE(io && panel_dev_config && ret_panel, ESP_ERR_INVALID_ARG, TAG, "invalid argument");

    esp_err_t ret = ESP_OK;
    sh8501_panel_t *sh8501 = NULL;
    sh8501 = calloc(1, sizeof(sh8501_panel_t));
    ESP_GOTO_ON_FALSE(sh8501, ESP_ERR_NO_MEM, err, TAG, "no mem for sh8501 panel");

    if (panel_dev_config->reset_gpio_num >= 0) {
        gpio_config_t io_conf = {
            .mode = GPIO_MODE_OUTPUT,
            .pin_bit_mask = 1ULL << panel_dev_config->reset_gpio_num,
        };
        ESP_GOTO_ON_ERROR(gpio_config(&io_conf), err, TAG, "configure GPIO for RST line failed");
    }

    switch (panel_dev_config->rgb_ele_order) {
    case LCD_RGB_ELEMENT_ORDER_RGB:
        sh8501->madctl_val = 0;
        break;
    case LCD_RGB_ELEMENT_ORDER_BGR:
        sh8501->madctl_val |= LCD_CMD_BGR_BIT;
        break;
    default:
        ESP_GOTO_ON_FALSE(false, ESP_ERR_NOT_SUPPORTED, err, TAG, "unsupported color element order");
        break;
    }

    uint8_t fb_bits_per_pixel = 0;
    switch (panel_dev_config->bits_per_pixel) {
    case 16: // RGB565
        sh8501->colmod_val = 0x55;
        fb_bits_per_pixel = 16;
        break;
    case 18: // RGB666
        sh8501->colmod_val = 0x66;
        // each color component (R/G/B) should occupy the 6 high bits of a byte, which means 3 full bytes are required for a pixel
        fb_bits_per_pixel = 24;
        break;
    case 24: // RGB888
        sh8501->colmod_val = 0x77;
        fb_bits_per_pixel = 24;
        break;
    default:
        ESP_GOTO_ON_FALSE(false, ESP_ERR_NOT_SUPPORTED, err, TAG, "unsupported pixel width");
        break;
    }

    sh8501->io = io;
    sh8501->reset_gpio_num = panel_dev_config->reset_gpio_num;
    sh8501->fb_bits_per_pixel = fb_bits_per_pixel;
    sh8501_vendor_config_t *vendor_config = (sh8501_vendor_config_t *)panel_dev_config->vendor_config;
    if (vendor_config) {
        sh8501->init_cmds = vendor_config->init_cmds;
        sh8501->init_cmds_size = vendor_config->init_cmds_size;
        sh8501->flags.use_qspi_interface = vendor_config->flags.use_qspi_interface;
    }
    sh8501->flags.reset_level = panel_dev_config->flags.reset_active_high;
    sh8501->base.del = panel_sh8501_del;
    sh8501->base.reset = panel_sh8501_reset;
    sh8501->base.init = panel_sh8501_init;
    sh8501->base.draw_bitmap = panel_sh8501_draw_bitmap;
    sh8501->base.invert_color = panel_sh8501_invert_color;
    sh8501->base.set_gap = panel_sh8501_set_gap;
    sh8501->base.mirror = panel_sh8501_mirror;
    sh8501->base.swap_xy = panel_sh8501_swap_xy;
    sh8501->base.disp_on_off = panel_sh8501_disp_on_off;
    *ret_panel = &(sh8501->base);
    ESP_LOGD(TAG, "new sh8501 panel @%p", sh8501);

    return ESP_OK;

err:
    if (sh8501) {
        if (panel_dev_config->reset_gpio_num >= 0) {
            gpio_reset_pin(panel_dev_config->reset_gpio_num);
        }
        free(sh8501);
    }
    return ret;
}

static esp_err_t tx_param(sh8501_panel_t *sh8501, esp_lcd_panel_io_handle_t io, int lcd_cmd, const void *param, size_t param_size)
{
    if (sh8501->flags.use_qspi_interface) {
        lcd_cmd &= 0xff;
        lcd_cmd <<= 8;
        lcd_cmd |= LCD_OPCODE_WRITE_CMD << 24;
    }
    return esp_lcd_panel_io_tx_param(io, lcd_cmd, param, param_size);
}

static esp_err_t tx_color(sh8501_panel_t *sh8501, esp_lcd_panel_io_handle_t io, int lcd_cmd, const void *param, size_t param_size)
{
    if (sh8501->flags.use_qspi_interface) {
        lcd_cmd &= 0xff;
        lcd_cmd <<= 8;
        lcd_cmd |= LCD_OPCODE_WRITE_COLOR << 24;
    }
    return esp_lcd_panel_io_tx_color(io, lcd_cmd, param, param_size);
}

static esp_err_t panel_sh8501_del(esp_lcd_panel_t *panel)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);

    if (sh8501->reset_gpio_num >= 0) {
        gpio_reset_pin(sh8501->reset_gpio_num);
    }
    ESP_LOGD(TAG, "del sh8501 panel @%p", sh8501);
    free(sh8501);
    return ESP_OK;
}

static esp_err_t panel_sh8501_reset(esp_lcd_panel_t *panel)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    esp_lcd_panel_io_handle_t io = sh8501->io;

    // Perform hardware reset
    if (sh8501->reset_gpio_num >= 0) {
        // RoRoLee 补丁：复位时序对齐供应商 KAC lcd_init.c（RES 低 250ms + 释放后 250ms）。
        // 原值 10/150ms 对部分单体偏紧，配合下面补回的电源寄存器一起排查黑屏问题。
        gpio_set_level(sh8501->reset_gpio_num, sh8501->flags.reset_level);
        vTaskDelay(pdMS_TO_TICKS(250));
        gpio_set_level(sh8501->reset_gpio_num, !sh8501->flags.reset_level);
        vTaskDelay(pdMS_TO_TICKS(250));
    } else { // Perform software reset
        ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_SWRESET, NULL, 0), TAG, "send command failed");
        vTaskDelay(pdMS_TO_TICKS(80));
    }

    return ESP_OK;
}

