static esp_err_t panel_sh8501_set_gap(esp_lcd_panel_t *panel, int x_gap, int y_gap)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    sh8501->x_gap = x_gap;
    sh8501->y_gap = y_gap;
    return ESP_OK;
}

static esp_err_t panel_sh8501_disp_on_off(esp_lcd_panel_t *panel, bool on_off)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    esp_lcd_panel_io_handle_t io = sh8501->io;
    int command = 0;

    if (on_off) {
        command = LCD_CMD_DISPON;
    } else {
        command = LCD_CMD_DISPOFF;
    }
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, command, NULL, 0), TAG, "send command failed");
    return ESP_OK;
}

esp_err_t esp_lcd_panel_sh8501_set_brightness(esp_lcd_panel_handle_t panel, uint8_t brightness_percent)
{
    ESP_RETURN_ON_FALSE(panel, ESP_ERR_INVALID_ARG, TAG, "invalid panel handle");
    ESP_RETURN_ON_FALSE(brightness_percent <= 100, ESP_ERR_INVALID_ARG, TAG, "brightness percentage must be 0-100");

    sh8501_panel_context_t *panel_ctx = (sh8501_panel_context_t *)panel->user_data;
    ESP_RETURN_ON_FALSE(panel_ctx, ESP_ERR_INVALID_STATE, TAG, "panel context not initialized");
    ESP_RETURN_ON_FALSE(panel_ctx->apply_brightness, ESP_ERR_NOT_SUPPORTED, TAG, "brightness control not supported");

    ESP_RETURN_ON_ERROR(panel_ctx->apply_brightness(panel_ctx->driver_data, brightness_percent), TAG,
                        "apply brightness failed");

    return ESP_OK;
}
