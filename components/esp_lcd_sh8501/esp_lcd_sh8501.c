static esp_err_t panel_sh8501_init(esp_lcd_panel_t *panel)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    esp_lcd_panel_io_handle_t io = sh8501->io;
    const sh8501_lcd_init_cmd_t *init_cmds = NULL;
    uint16_t init_cmds_size = 0;
    bool is_cmd_overwritten = false;

    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_MADCTL, (uint8_t[]) {
        sh8501->madctl_val,
    }, 1), TAG, "send command failed");
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_COLMOD, (uint8_t[]) {
        sh8501->colmod_val,
    }, 1), TAG, "send command failed");

    // vendor specific initialization, it can be different between manufacturers
    // should consult the LCD supplier for initialization sequence code
    if (sh8501->init_cmds) {
        init_cmds = sh8501->init_cmds;
        init_cmds_size = sh8501->init_cmds_size;
    } else {
        init_cmds = vendor_specific_init_default;
        init_cmds_size = sizeof(vendor_specific_init_default) / sizeof(sh8501_lcd_init_cmd_t);
    }

    for (int i = 0; i < init_cmds_size; i++) {
        // Check if the command has been used or conflicts with the internal
        switch (init_cmds[i].cmd) {
        case LCD_CMD_MADCTL:
            is_cmd_overwritten = true;
            sh8501->madctl_val = ((uint8_t *)init_cmds[i].data)[0];
            break;
        case LCD_CMD_COLMOD:
            is_cmd_overwritten = true;
            sh8501->colmod_val = ((uint8_t *)init_cmds[i].data)[0];
            break;
        default:
            is_cmd_overwritten = false;
            break;
        }

        if (is_cmd_overwritten) {
            ESP_LOGW(TAG, "The %02Xh command has been used and will be overwritten by external initialization sequence", init_cmds[i].cmd);
        }

        ESP_RETURN_ON_ERROR(tx_param(sh8501, io, init_cmds[i].cmd, init_cmds[i].data, init_cmds[i].data_bytes), TAG,
                            "send command failed");
        vTaskDelay(pdMS_TO_TICKS(init_cmds[i].delay_ms));
    }
    ESP_LOGD(TAG, "send init commands success");

    return ESP_OK;
}

static esp_err_t panel_sh8501_draw_bitmap(esp_lcd_panel_t *panel, int x_start, int y_start, int x_end, int y_end, const void *color_data)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    assert((x_start < x_end) && (y_start < y_end) && "start position must be smaller than end position");
    esp_lcd_panel_io_handle_t io = sh8501->io;

    x_start += sh8501->x_gap;
    x_end += sh8501->x_gap;
    y_start += sh8501->y_gap;
    y_end += sh8501->y_gap;

    // define an area of frame memory where MCU can access
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_CASET, (uint8_t[]) {
        (x_start >> 8) & 0xFF,
        x_start & 0xFF,
        ((x_end - 1) >> 8) & 0xFF,
        (x_end - 1) & 0xFF,
    }, 4), TAG, "send command failed");
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_RASET, (uint8_t[]) {
        (y_start >> 8) & 0xFF,
        y_start & 0xFF,
        ((y_end - 1) >> 8) & 0xFF,
        (y_end - 1) & 0xFF,
    }, 4), TAG, "send command failed");
    // transfer frame buffer
    size_t len = (x_end - x_start) * (y_end - y_start) * sh8501->fb_bits_per_pixel / 8;
    ESP_RETURN_ON_ERROR(tx_color(sh8501, io, LCD_CMD_RAMWR, color_data, len), TAG, "send color data failed");

    return ESP_OK;
}

static esp_err_t panel_sh8501_invert_color(esp_lcd_panel_t *panel, bool invert_color_data)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    esp_lcd_panel_io_handle_t io = sh8501->io;
    int command = 0;
    if (invert_color_data) {
        command = LCD_CMD_INVON;
    } else {
        command = LCD_CMD_INVOFF;
    }
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, command, NULL, 0), TAG, "send command failed");
    return ESP_OK;
}

static esp_err_t panel_sh8501_mirror(esp_lcd_panel_t *panel, bool mirror_x, bool mirror_y)
{
    sh8501_panel_t *sh8501 = __containerof(panel, sh8501_panel_t, base);
    esp_lcd_panel_io_handle_t io = sh8501->io;
    esp_err_t ret = ESP_OK;

    if (mirror_x) {
        sh8501->madctl_val |= BIT(6);
    } else {
        sh8501->madctl_val &= ~BIT(6);
    }
    if (mirror_y) {
        ESP_LOGE(TAG, "mirror_y is not supported by this panel");
        ret = ESP_ERR_NOT_SUPPORTED;
    }
    ESP_RETURN_ON_ERROR(tx_param(sh8501, io, LCD_CMD_MADCTL, (uint8_t[]) {
        sh8501->madctl_val
    }, 1), TAG, "send command failed");
    return ret;
}

